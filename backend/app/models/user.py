"""
User models.

These mirror database/schema.sql exactly (types, nullability, generated columns).
schema.sql is the source of truth for DDL; the ORM never creates tables in MySQL.
"""

from datetime import datetime

from app.utils.timeutil import utcnow

from sqlalchemy import (
    JSON, BigInteger, Boolean, Column, Computed, Date, DateTime, ForeignKey,
    Integer, Numeric, String, Time,
)
from sqlalchemy.orm import relationship

from app.config.database import Base

# BIGINT in MySQL, plain INTEGER on SQLite (so SQLite can autoincrement if ever used)
PK = BigInteger().with_variant(Integer, "sqlite")


class UserRole:
    USER = "USER"
    ADMIN = "ADMIN"


class TokenType:
    REFRESH = "REFRESH"
    PASSWORD_RESET = "PASSWORD_RESET"
    EMAIL_VERIFY = "EMAIL_VERIFY"


class User(Base):
    __tablename__ = "users"

    id = Column(PK, primary_key=True, autoincrement=True)
    email = Column(String(255), unique=True, nullable=False)
    password_hash = Column(String(255), nullable=False)
    full_name = Column(String(255), nullable=False)
    phone = Column(String(20))
    date_of_birth = Column(Date)
    gender = Column(String(10), default="OTHER")          # ENUM(MALE, FEMALE, OTHER)
    role = Column(String(10), default=UserRole.USER)      # ENUM(USER, ADMIN)
    is_active = Column(Boolean, default=True)
    email_verified = Column(Boolean, default=False)
    quiet_hours_start = Column(Time, nullable=True)
    quiet_hours_end = Column(Time, nullable=True)
    reminder_lead_time_minutes = Column(Integer, default=15, nullable=False)
    timezone = Column(String(64), default="UTC", nullable=False)
    totp_secret = Column(String(64), nullable=True)
    totp_enabled = Column(Boolean, default=False, nullable=False)
    last_login = Column(DateTime)
    created_at = Column(DateTime, default=utcnow)
    updated_at = Column(DateTime, default=utcnow, onupdate=utcnow)

    profile = relationship(
        "UserProfile", back_populates="user", uselist=False, cascade="all, delete-orphan"
    )
    tokens = relationship("UserToken", back_populates="user", cascade="all, delete-orphan")
    health_assessments = relationship(
        "HealthAssessment", back_populates="user", cascade="all, delete-orphan"
    )
    medicines = relationship("Medicine", back_populates="user", cascade="all, delete-orphan")
    exercise_logs = relationship("ExerciseLog", back_populates="user", cascade="all, delete-orphan")
    sleep_logs = relationship("SleepLog", back_populates="user", cascade="all, delete-orphan")
    hydration_logs = relationship("HydrationLog", back_populates="user", cascade="all, delete-orphan")
    nutrition_logs = relationship("NutritionLog", back_populates="user", cascade="all, delete-orphan")
    wellness_goals = relationship("WellnessGoal", back_populates="user", cascade="all, delete-orphan")
    emergency_card = relationship("EmergencyCard", back_populates="user", cascade="all, delete-orphan", uselist=False)
    symptom_logs = relationship("SymptomLog", back_populates="user", cascade="all, delete-orphan")
    doctor_appointments = relationship("DoctorAppointment", back_populates="user", cascade="all, delete-orphan")
    doctor_shares = relationship("DoctorShare", back_populates="user", cascade="all, delete-orphan")

    @property
    def is_admin(self) -> bool:
        return self.role == UserRole.ADMIN

    def __repr__(self):
        return f"<User id={self.id} email={self.email!r} role={self.role}>"


class UserProfile(Base):
    __tablename__ = "user_profiles"

    id = Column(PK, primary_key=True, autoincrement=True)
    user_id = Column(PK, ForeignKey("users.id", ondelete="CASCADE"), unique=True, nullable=False)
    height_cm = Column(Numeric(5, 2))
    weight_kg = Column(Numeric(6, 2))
    # Generated by MySQL from weight/height (see schema.sql); read-only for the ORM.
    bmi = Column(Numeric(5, 2), Computed("weight_kg / POW(height_cm/100, 2)", persisted=True))
    waist_circumference_cm = Column(Numeric(5, 2))
    blood_type = Column(String(5))
    allergies = Column(JSON)
    existing_conditions = Column(JSON)
    family_history = Column(JSON)
    exercise_frequency = Column(String(20))
    sleep_duration_hours = Column(Numeric(4, 2))
    smoking_status = Column(String(10))
    alcohol_consumption = Column(String(15))
    cholesterol_level = Column(String(20))
    diet_type = Column(String(100))
    water_intake_goal_ml = Column(Integer, default=2500)
    emergency_contact_name = Column(String(255))
    emergency_contact_phone = Column(String(20))
    updated_at = Column(DateTime, default=utcnow, onupdate=utcnow)

    user = relationship("User", back_populates="profile")


class UserToken(Base):
    """Hashed refresh / password-reset / email-verification tokens."""

    __tablename__ = "user_tokens"

    id = Column(PK, primary_key=True, autoincrement=True)
    user_id = Column(PK, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    token_hash = Column(String(64), unique=True, nullable=False)
    token_type = Column(String(20), nullable=False)
    expires_at = Column(DateTime, nullable=False)
    used_at = Column(DateTime)
    revoked = Column(Boolean, default=False)
    ip_address = Column(String(45), nullable=True)
    user_agent = Column(String(500), nullable=True)
    device_name = Column(String(100), nullable=True)
    created_at = Column(DateTime, default=utcnow)

    user = relationship("User", back_populates="tokens")

    def is_usable(self, now: datetime | None = None) -> bool:
        now = now or utcnow()
        return not self.revoked and self.used_at is None and now < self.expires_at
